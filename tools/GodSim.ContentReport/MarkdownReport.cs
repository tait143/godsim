using System;
using System.Collections.Generic;
using System.Text;
using GodSim.Core;

namespace GodSim.ContentReport
{
    /// <summary>Generates docs/CONTENT_REFERENCE.md from a <see cref="ContentModel"/>. Output is deterministic (no timestamps).</summary>
    internal sealed partial class MarkdownReport
    {
        public const string RegenerateCommand = "dotnet run --project tools/GodSim.ContentReport -c Release";
        public const string FallbackCommand = "build/checks/ContentReport/run.sh";

        private readonly ContentModel _m;
        private readonly string _fingerprint;
        private readonly StringBuilder _sb = new StringBuilder(256 * 1024);

        public MarkdownReport(ContentModel model, string fingerprint) { _m = model; _fingerprint = fingerprint; }

        public string Generate()
        {
            Header();
            Contents();
            Races();
            Ages();
            Technologies();
            BuildingsSection();
            GodPowers();
            Balance();
            Footer();
            return _sb.ToString();
        }

        // ------------------------------------------------------------------ helpers
        private void H(int level, string text) { _sb.Append('\n').Append('#', level).Append(' ').Append(text).Append("\n\n"); }
        private void P(string text) { _sb.Append(text).Append("\n\n"); }
        private void Line(string text) { _sb.Append(text).Append('\n'); }
        private void Table(MdTable t) { t.WriteTo(_sb); }
        private void Mermaid(List<string> lines)
        {
            _sb.Append("```mermaid\n");
            foreach (var l in lines) _sb.Append(l).Append('\n');
            _sb.Append("```\n\n");
        }

        private string B(BuildingType t) => _m.BuildingName(t);
        private string Age(int a) => _m.AgeName(a);
        private string Age(AgeId a) => _m.AgeName((int)a);

        private static string Amounts(ResourceAmount[] list, string unit = "")
        {
            if (list == null || list.Length == 0) return "—";
            var parts = new List<string>();
            foreach (var x in list) parts.Add(Md.N(x.Amount) + unit + " " + x.Type);
            return string.Join(", ", parts);
        }

        private static string Services(ServiceAmount[] list)
        {
            if (list == null || list.Length == 0) return "—";
            var parts = new List<string>();
            foreach (var x in list) parts.Add(Md.N(x.Amount) + " " + x.Type);
            return string.Join(", ", parts);
        }

        // ------------------------------------------------------------------ header
        private void Header()
        {
            Line("<!--");
            Line("  AUTO-GENERATED FILE. DO NOT EDIT BY HAND.");
            Line("  Generated by tools/GodSim.ContentReport from the content catalogs in Assets/GodSim/Core/.");
            Line("  Regenerate: " + RegenerateCommand);
            Line("-->");
            Line("");
            Line("# GodSim Content Reference");
            Line("");
            Line("> **Auto-generated, do not edit by hand.** This file is rebuilt from the content catalogs");
            Line("> (`RaceCatalog`, `AgeCatalog`, `TechCatalog`, `BuildingCatalog`, `GodPowerCatalog`). Change the data, then regenerate:");
            Line(">");
            Line("> ```bash");
            Line("> " + RegenerateCommand);
            Line("> # if a systems module does not compile yet, use the content-only check build:");
            Line("> " + FallbackCommand);
            Line("> ```");
            Line(">");
            Line("> CI gate: add `--check` (exit 1 on content errors). JSON dump for the web viewer: `--json <file>`.");
            Line("");

            var t = new MdTable("Content", ">Count");
            t.Row("Races", _m.Races.Count);
            t.Row("Ages", _m.Ages.Count);
            t.Row("Technologies", _m.Techs.Count);
            t.Row("Buildings", _m.Buildings.Count);
            t.Row("God powers", _m.Powers.Count);
            t.Row("Errors / warnings / notes", _m.ErrorCount + " / " + _m.WarningCount + " / " + _m.Count(Severity.Info));
            Table(t);
            string status = _m.Load.Frozen ? "frozen successfully" : "**failed to freeze** (report built from the unfrozen data)";
            P("Database " + status + ". Catalogs loaded: " + Md.Join(_m.Load.CatalogsLoaded) + "." +
              (_m.Load.CatalogErrors.Count > 0 ? " **Missing/failed: " + _m.Load.CatalogErrors.Count + "** (see [Warnings](#warnings))." : "") +
              " Content fingerprint `" + _fingerprint + "`.");
            P("Units: 1 tick = 1 day, " + SimTime.TicksPerYear + " ticks per year. Rates marked *per worker* are per staffed worker per tick; services are per fully staffed building per tick. " +
              "Shading uses five dots: ●●●●● = 1.0, ○○○○○ = 0.");
        }

        private void Contents()
        {
            H(2, "Contents");
            Line("1. [Races](#races)");
            Line("2. [Ages](#ages)");
            Line("3. [Technologies](#technologies)");
            Line("4. [Buildings](#buildings)");
            Line("5. [God powers](#god-powers)");
            Line("6. [Balance sanity](#balance-sanity)");
            Line("   - [Warnings](#warnings)");
            Line("");
        }

        private void Footer()
        {
            Line("---");
            Line("");
            Line("*Generated by `tools/GodSim.ContentReport`. Do not edit by hand; regenerate with `" + RegenerateCommand + "`.*");
        }

        // ------------------------------------------------------------------ races
        private void Races()
        {
            H(2, "Races");
            if (_m.Races.Count == 0) { P("_No races registered._"); return; }

            H(3, "Comparison");
            var t = new MdTable("Race", ">Lifespan", ">Adult", ">Elder", ">Fertility/yr", ">Max kids", ">Food/tick", ">Food/yr", ">Health", ">Disease res.", ">Build", ">Research", ">Faith", ">Military", ">Trade", ">Move");
            foreach (var r in _m.Races)
                t.Row("**" + r.Name + "**", Md.N(r.LifeExpectancy, 0), Md.N(r.AdulthoodAge, 0), Md.N(r.ElderAge, 0), Md.F(r.FertilityPerYear, 2), r.MaxChildren,
                    Md.F(r.FoodPerTick, 3), Md.N(r.FoodPerTick * SimTime.TicksPerYear, 1), Md.F(r.BaseHealth), Md.F(r.DiseaseResistance), Md.F(r.BuildSpeed), Md.F(r.ResearchRate),
                    Md.F(r.FaithRate), Md.F(r.MilitaryStrength), Md.F(r.TradeAptitude), Md.F(r.MoveSpeed));
            Table(t);
            P("Ages in years. Aptitudes are multipliers (1.00 = baseline).");

            H(3, "Personality and layout");
            var p = new MdTable("Race", "^Aggression", "^Expansion", "^Piety", "^Industry", "^Curiosity", "^Diplomacy", "^Xenophobia", "^Mercantile", ">Spacing", ">Compact", ">Roads");
            foreach (var r in _m.Races)
                p.Row("**" + r.Name + "**", Shade(r.Aggression), Shade(r.Expansionism), Shade(r.Piety), Shade(r.Industriousness), Shade(r.Curiosity),
                    Shade(r.Diplomacy), Shade(r.Xenophobia), Shade(r.Mercantilism), r.MinSettlementSpacing, Md.F(r.Compactness), Md.F(r.RoadAffinity));
            Table(p);

            H(3, "Habitability by biome");
            var headers = new List<string> { "Biome" };
            foreach (var r in _m.Races) headers.Add("^" + r.Name);
            headers.Add("^Best for");
            var h = new MdTable(headers.ToArray());
            for (int bi = 0; bi < Counts.Biomes; bi++)
            {
                var row = new List<object> { ((Biome)bi).ToString() };
                float best = 0f; string bestName = "—";
                foreach (var r in _m.Races)
                {
                    float v = r.BiomeHabitability != null && bi < r.BiomeHabitability.Length ? r.BiomeHabitability[bi] : 0f;
                    row.Add(Shade(v));
                    if (v > best + 1e-4f) { best = v; bestName = r.Name; }
                    else if (best > 0f && Math.Abs(v - best) <= 1e-4f) bestName += ", " + r.Name;
                }
                row.Add(best > 0f ? bestName : "—");
                h.Row(row.ToArray());
            }
            Table(h);

            H(3, "Production multipliers");
            headers = new List<string> { "Resource" };
            foreach (var r in _m.Races) headers.Add(">" + r.Name);
            var pm = new MdTable(headers.ToArray());
            for (int res = 0; res < Counts.Resources; res++)
            {
                var row = new List<object> { ((ResourceType)res).ToString() };
                foreach (var r in _m.Races)
                {
                    float v = r.ProductionMultiplier != null && res < r.ProductionMultiplier.Length ? r.ProductionMultiplier[res] : 1f;
                    string s = "×" + Md.F(v);
                    row.Add(v > 1.001f ? "**" + s + "**" : v < 0.999f ? "*" + s + "*" : s);
                }
                pm.Row(row.ToArray());
            }
            Table(pm);
            P("**Bold** = above baseline, *italic* = below.");

            H(3, "Affinity matrix");
            headers = new List<string> { "Feels about →" };
            foreach (var r in _m.Races) headers.Add(">" + r.Name);
            var am = new MdTable(headers.ToArray());
            foreach (var r in _m.Races)
            {
                var row = new List<object> { "**" + r.Name + "**" };
                foreach (var o in _m.Races)
                {
                    int oi = (int)o.Id;
                    row.Add(r.RaceAffinity != null && oi < r.RaceAffinity.Length ? Md.Signed(r.RaceAffinity[oi]) : "—");
                }
                am.Row(row.ToArray());
            }
            Table(am);
            P("Rows are the race that feels, columns the race it feels about (−1 hatred … +1 kinship).");

            H(3, "Architecture");
            var ar = new MdTable("Race", "Style tag", "Roof", ">Height", ">Width", ">Round", "Special", "Wall", "Roof color", "Trim", "Accent");
            foreach (var r in _m.Races)
            {
                var a = r.Architecture ?? new ArchitectureStyle();
                var special = new List<string>();
                if (a.BuildsUnderground) special.Add("underground");
                if (a.BuildsInTrees) special.Add("in trees");
                if (a.BuildsOnStilts) special.Add("on stilts");
                ar.Row("**" + r.Name + "**", a.StyleTag, a.Roof, Md.F(a.HeightScale), Md.F(a.WidthScale), Md.F(a.Roundness), Md.Join(special),
                    "`" + Md.Color(a.WallColor) + "`", "`" + Md.Color(a.RoofColor) + "`", "`" + Md.Color(a.TrimColor) + "`", "`" + Md.Color(a.AccentColor) + "`");
            }
            Table(ar);

            H(3, "Unique and favored buildings");
            var ub = new MdTable("Race", "Unique buildings", "Favored buildings (AI bias)", "Racial techs");
            foreach (var r in _m.Races)
            {
                var uniques = new List<string>();
                foreach (var u in r.UniqueBuildings ?? new BuildingType[0])
                {
                    var d = _m.BuildingDef(u);
                    uniques.Add(B(u) + (d != null ? " (" + Age(_m.BuildingFirstAge[(int)r.Id, (int)u]) + ")" : ""));
                }
                var fav = new List<string>();
                foreach (var f in r.FavoredBuildings ?? new BuildingType[0]) fav.Add(B(f));
                var techs = new List<string>();
                foreach (var tch in _m.Techs) if (tch.AllowedRaces != RaceMask.All && tch.AllowedRaces.Allows(r.Id)) techs.Add(tch.Name);
                ub.Row("**" + r.Name + "**", Md.Join(uniques), Md.Join(fav), Md.Join(techs));
            }
            Table(ub);

            H(3, "Descriptions");
            foreach (var r in _m.Races)
                Line("- **" + r.Name + "** (`" + Md.Color(r.BannerColor) + "`): " + Md.Cell(r.Description));
            Line("");
        }

        private static string Shade(float v) => Md.Dots(v) + " " + Md.F(v);

        // ------------------------------------------------------------------ ages
        private void Ages()
        {
            H(2, "Ages");
            if (_m.Ages.Count == 0) { P("_No ages registered._"); return; }
            var t = new MdTable(">#", "Age", ">Research threshold", ">Δ from previous", ">Prev-age techs", ">Min pop.", ">Min settl.", ">Production", ">Research", ">Lifespan", ">Health", ">Soldier str.", ">Techs");
            float prev = 0f;
            foreach (var a in _m.Ages)
            {
                int i = (int)a.Id;
                t.Row(i, "**" + a.Name + "**", Md.N(a.ResearchThreshold, 0), i == 0 ? "—" : "+" + Md.N(a.ResearchThreshold - prev, 0),
                    i == 0 ? "—" : a.RequiredTechsFromPreviousAge + " of " + _m.TechsOf(i - 1).Count,
                    a.MinPopulation, a.MinSettlements, Md.Pct(a.ProductionBonus), Md.Pct(a.ResearchBonus),
                    "+" + Md.N(a.LifespanBonusYears, 1) + " y", Md.Signed(a.HealthBonus), "×" + Md.F(a.BaseSoldierStrength), _m.TechsOf(i).Count);
                prev = a.ResearchThreshold;
            }
            Table(t);
            P("Research threshold = cumulative `Civilization.TotalResearch` needed to enter the age; *Prev-age techs* = `RequiredTechsFromPreviousAge` of the techs registered for the previous age. Bonuses are additive while in the age.");

            H(3, "Timeline");
            Mermaid(AgeFlow());
            _sb.Append("```text\n");
            float max = 1f;
            foreach (var a in _m.Ages) max = Math.Max(max, a.ResearchThreshold);
            double logMax = Math.Log10(max + 1);
            foreach (var a in _m.Ages)
            {
                int bar = logMax <= 0 ? 0 : (int)Math.Round(40 * Math.Log10(a.ResearchThreshold + 1) / logMax);
                _sb.Append(a.Id.ToString().PadRight(12)).Append(Md.N(a.ResearchThreshold, 0).PadLeft(10)).Append(" RP  ")
                   .Append(new string('█', bar)).Append(new string('·', 40 - bar))
                   .Append("  pop ").Append(a.MinPopulation.ToString().PadLeft(4))
                   .Append('\n');
            }
            _sb.Append("(bar = research threshold, log scale)\n```\n\n");

            H(3, "Age descriptions");
            foreach (var a in _m.Ages)
            {
                Line("- **" + a.Name + "** (`" + Md.Color(a.ThemeColor) + "`): " + Md.Cell(a.Description));
                if (!string.IsNullOrEmpty(a.ArchitectureNotes)) Line("  - *Architecture:* " + Md.Cell(a.ArchitectureNotes));
            }
            Line("");
        }

        private List<string> AgeFlow()
        {
            var l = new List<string> { "flowchart TD" };
            foreach (var a in _m.Ages)
                l.Add("  " + Md.Id("age_", a.Id.ToString()) + "[\"" + Md.Label(a.Name) + "\"]");
            for (int i = 1; i < _m.Ages.Count; i++)
            {
                var prev = _m.Ages[i - 1]; var cur = _m.Ages[i];
                string label = Md.N(cur.ResearchThreshold, 0) + " RP, " + cur.RequiredTechsFromPreviousAge + " techs, pop " + cur.MinPopulation +
                               (cur.MinSettlements > 1 ? ", " + cur.MinSettlements + " towns" : "");
                l.Add("  " + Md.Id("age_", prev.Id.ToString()) + " -->|\"" + Md.Label(label) + "\"| " + Md.Id("age_", cur.Id.ToString()));
            }
            return l;
        }
    }
}
