#!/usr/bin/env bash
# new-module-check.sh: create build/checks/<Module>/<Module>.Tests.csproj from build/checks/_template.
#
# Usage: scripts/new-module-check.sh [--force] [--stdout] <Module> <CorePath> [TestsPath]
#   Module     check name, e.g. SettlementsPlanning   (letters/digits, starts with a letter)
#   CorePath   folder under Assets/GodSim/Core, e.g. Settlements/Planning
#   TestsPath  folder under Assets/GodSim/Tests/EditMode (default: same as CorePath)
#   --force    overwrite an existing project file
#   --stdout   print the project instead of writing it
#
# Then: cd build/checks/<Module> && dotnet test -nologo -v q --disable-build-servers
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TEMPLATE="$ROOT/build/checks/_template/Template.Tests.csproj"
FORCE=0
STDOUT=0
POS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --force) FORCE=1; shift ;;
        --stdout) STDOUT=1; shift ;;
        -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
        -*) echo "error: unknown option: $1" >&2; exit 2 ;;
        *) POS+=("$1"); shift ;;
    esac
done
if [[ ${#POS[@]} -lt 2 || ${#POS[@]} -gt 3 ]]; then
    sed -n '4,8p' "$0" >&2; exit 2
fi

MODULE="${POS[0]}"
CORE_PATH="${POS[1]%/}"
TESTS_PATH="${POS[2]:-$CORE_PATH}"
TESTS_PATH="${TESTS_PATH%/}"

[[ "$MODULE" =~ ^[A-Za-z][A-Za-z0-9]*$ ]] || { echo "error: invalid module name '$MODULE'" >&2; exit 2; }
[[ "$MODULE" != "_template" && "$MODULE" != "Infra" ]] || { echo "error: '$MODULE' is reserved" >&2; exit 2; }
for p in "$CORE_PATH" "$TESTS_PATH"; do
    # Relative, slash-separated identifiers only: no '..', no leading '/', nothing sed or MSBuild would interpret.
    if [[ ! "$p" =~ ^[A-Za-z0-9_]+(/[A-Za-z0-9_]+)*$ ]]; then
        echo "error: invalid path '$p' (expected e.g. Settlements/Planning)" >&2; exit 2
    fi
done
[[ "$CORE_PATH" != Contracts* ]] || { echo "error: Contracts are always compiled; pick your module folder" >&2; exit 2; }
[[ -f "$TEMPLATE" ]] || { echo "error: template not found: $TEMPLATE" >&2; exit 2; }
grep -q 'Core/MODULE/' "$TEMPLATE" || { echo "error: template has no Core/MODULE/ placeholder" >&2; exit 2; }

[[ -d "$ROOT/Assets/GodSim/Core/$CORE_PATH" ]] || echo "warning: Assets/GodSim/Core/$CORE_PATH does not exist yet" >&2
[[ -d "$ROOT/Assets/GodSim/Tests/EditMode/$TESTS_PATH" ]] || echo "warning: Assets/GodSim/Tests/EditMode/$TESTS_PATH does not exist yet" >&2

render() {
    sed -e "s|Core/MODULE/|Core/${CORE_PATH}/|g" \
        -e "s|EditMode/MODULE/|EditMode/${TESTS_PATH}/|g" \
        -e "s|<!-- TEMPLATE for module checks\..*-->|<!-- Isolated check for ${MODULE} (generated by scripts/new-module-check.sh). -->|" \
        -e "s|<!-- your module + your tests (edit these two lines) -->|<!-- ${MODULE}: Core/${CORE_PATH} + EditMode/${TESTS_PATH} -->|" \
        "$TEMPLATE"
}

if [[ $STDOUT -eq 1 ]]; then render; exit 0; fi

DIR="$ROOT/build/checks/$MODULE"
OUT="$DIR/$MODULE.Tests.csproj"
if [[ -e "$OUT" && $FORCE -eq 0 ]]; then
    echo "error: $OUT already exists (use --force to overwrite)" >&2; exit 1
fi
mkdir -p "$DIR"
render > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "created ${OUT#"$ROOT"/}"
echo "next:   cd build/checks/$MODULE && dotnet test -nologo -v q --disable-build-servers"
